"""Break one property at a time, require the matching test to fail, restore, retest.

Each mutant is applied to a temporary copy of the source in place, the targeted tests
are run, and the original bytes are restored in a `finally` block. Do not edit the
target files while this runs. Raw outputs go to test-results/.
"""
from pathlib import Path
import hashlib
import json
import os
import subprocess

ROOT = Path(__file__).resolve().parents[1]
FORGE = str(Path.home() / ".foundry/bin/forge.exe") if os.name == "nt" else "forge"
os.environ["SVM_HOME"] = str(ROOT / ".toolchain/svm")
Q2 = json.loads((ROOT / "model/weights.json").read_text(encoding="utf-8"))["quantized"]["q2"]

CASES = [
    # (name, file, original, mutant, forge filter args, text that must appear in the failure)
    ("frozen-guard", "src/GuardedWallet.sol",
     'require(!frozen, "frozen");', "/* MUTANT: frozen check removed */",
     ["--match-contract", "SpendguardInvariantTest"], "invariant_FrozenWalletCannotSpend"),
    ("model-scale", "src/SpendguardModel.sol",
     f"return acc >> {Q2};", f"return acc >> {Q2 - 1};",
     ["--match-test", "test_ModelParityWithPythonVectors"], "test_ModelParityWithPythonVectors"),
    ("gap-feature", "src/SpendguardReactive.sol",
     "x[1] = _log2fx(dt + 1);", "x[1] = _log2fx(dt + 2);",
     ["--match-test", "test_SequenceParityFeaturesScoresAndFirstFreeze"], "test_SequenceParity"),
]


def forge(*args):
    r = subprocess.run([FORGE, "test", "--root", str(ROOT), "-vv", *args],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    return r.returncode, r.stdout + r.stderr


def main():
    logs = ROOT / "test-results"
    logs.mkdir(exist_ok=True)
    rows = []
    for name, file, old, new, filt, must in CASES:
        path = ROOT / file
        original = path.read_bytes()
        source = original.decode()
        if source.count(old) != 1:
            raise RuntimeError(f"{name}: mutation target must be unique")
        try:
            path.write_text(source.replace(old, new), encoding="utf-8", newline="\n")
            code, out = forge(*filt)
            (logs / f"mutation-{name}.txt").write_text(out, encoding="utf-8")
            killed = code != 0 and "[FAIL" in out and must in out
        finally:
            path.write_bytes(original)
        if not killed:
            raise RuntimeError(f"{name}: mutant survived")
        rows.append((name, file, old, new, " ".join(filt), hashlib.sha256(original).hexdigest()))
        print(f"{name}: mutant killed, source restored")
    code, out = forge()
    (logs / "restored-pass.txt").write_text(out, encoding="utf-8")
    if code:
        raise RuntimeError("restored suite failed")
    md = ["# Mutation check", "", "Generated by `tools/mutation_check.py`. Each row: the mutant made the listed tests "
          "fail (nonzero exit, `[FAIL` in output); the original bytes were restored and the whole suite passed again "
          "([raw](restored-pass.txt)).", "",
          "| Mutant | File | Original | Mutated | Tests run | Restored SHA-256 |", "|---|---|---|---|---|---|"]
    for name, file, old, new, filt, h in rows:
        md.append(f"| [{name}](mutation-{name}.txt) | `{file}` | `{old}` | `{new}` | `{filt}` | `{h[:16]}...` |")
    (logs / "MUTATION.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("all mutants killed; restored suite passes")


if __name__ == "__main__":
    main()
